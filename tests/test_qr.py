"""Tests for the dependency-free QR encoder (lanloom/qr.py).

The fixed SHA-256 vectors below were generated by this encoder and checked
module by module against the reference library ``segno`` (same version,
error correction level and mask; the automatic mask choice matched too).
"""

import hashlib
import xml.etree.ElementTree as ET

import pytest

from lanloom import qr

OTP = ("otpauth://totp/Lanloom%3Aadmin?secret=JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP"  # secret-scan: fake (RFC example secret)
       "&issuer=Lanloom&algorithm=SHA1&digits=6&period=30")
LONG = ("The quick brown fox jumps over the lazy dog 0123456789. " * 4)[:200]
BIG = ("abcdefghij" * 30)[:290]
UMLAUTS = "Grüße aus Bautzen: äöüß € 你好"
TEXTS = {"HELLO": "HELLO", "OTP": OTP, "LONG": LONG, "UML": UMLAUTS, "BIG": BIG}

# (text key, ecc, expected version, sha256 of the matrix as '0'/'1' rows joined by '\n')
VECTORS = [
    ("HELLO", "M", 1, "1fff7fd781f0f59edd796e0f79b20d68de6ecef41b47571460c4bbfbac1afe97"),
    ("HELLO", "L", 1, "554fa99a9aef3a2871ba7c7c80b885d71ec4789b3fece69ed099b0aa3c4009f4"),
    ("HELLO", "Q", 1, "30ee0f5998ddc4eb8a71766eac9217f56b226fd41f305f03f70ae2f4e5e394a9"),
    ("HELLO", "H", 1, "bf5188b5d40a4f1b7ae736874acaaae30a05ac59108e3423be980a42cb9ff40e"),
    ("OTP", "M", 7, "a5ddee5e1a80739e8aad234190f878ec8b2ae2efaef3b57aafac2a958735a8a7"),
    ("OTP", "L", 6, "c60a96e9c7eeb48b49e35cd2b413f21f05c9c9e131654a365b6bc2fe7c297498"),
    ("OTP", "H", 10, "fe554a7d4bf235908a4042573dfbd6c3cfe4b671f9d6a07e7dbc4c97e0912a71"),
    ("LONG", "M", 10, "aec0a39d8a21f110d3dc1a50c13e231e0d7e19c91636f574dcc038567a3de76f"),
    ("LONG", "Q", 12, "13e309020489304d1b1f639955c95ae18f54bdbd36e0c1fd30ffaf9e9756162b"),
    ("UML", "M", 3, "166141a6cb353fe25ac8313629fe536318cf1bcadd9fbdd95690f5a12e0ca66c"),
    ("BIG", "L", 11, "209e5282c9342ad2f8074a20d89671f62622b1dbaab72aa8cb3f991e48c4b4db"),
    ("BIG", "M", 13, "e229124ee46b97d2daa82323dfb3c154d5f0382300776052326aaafea605b082"),
]


def digest(matrix):
    rows = "\n".join("".join("1" if c else "0" for c in row) for row in matrix)
    return hashlib.sha256(rows.encode()).hexdigest()


@pytest.mark.parametrize("key,ecc,version,expected", VECTORS)
def test_fixed_vectors(key, ecc, version, expected):
    m = qr.encode(TEXTS[key], ecc)
    assert len(m) == len(m[0]) == version * 4 + 17
    assert digest(m) == expected


def test_default_level_is_m():
    assert qr.encode(OTP) == qr.encode(OTP, "M")


def test_version_grows_with_length():
    sizes = [len(qr.encode("x" * n)) for n in (1, 20, 60, 120, 200)]
    assert sizes == sorted(sizes) and len(set(sizes)) == len(sizes)
    assert len(qr.encode("x" * 14)) == 21 and len(qr.encode("x" * 15)) == 25


def test_stronger_level_needs_more_room():
    assert len(qr.encode(OTP, "H")) > len(qr.encode(OTP, "L"))


def test_finder_patterns_and_dark_module():
    m = qr.encode("HELLO")
    n = len(m)
    for ox, oy in ((0, 0), (n - 7, 0), (0, n - 7)):
        assert all(m[oy][ox + i] and m[oy + 6][ox + i] for i in range(7))
        assert m[oy + 3][ox + 3] and not m[oy + 1][ox + 1]
    assert m[n - 8][8]


def test_overflow_raises_value_error():
    with pytest.raises(ValueError):
        qr.encode("x" * 1000)
    with pytest.raises(ValueError):
        qr.encode("x" * 300, "H")
    with pytest.raises(ValueError):
        qr.encode("x", "Z")


def test_svg_is_well_formed_and_counts_modules():
    m = qr.encode(OTP)
    svg = qr.to_svg(m, scale=3, quiet=4)
    root = ET.fromstring(svg)
    assert root.tag.endswith("svg") and root.get("role") == "img"
    n = len(m) + 8
    assert root.get("viewBox") == f"0 0 {n} {n}"
    assert root.get("shape-rendering") == "crispEdges"
    paths = [e for e in root.iter() if e.tag.endswith("path")]
    assert len(paths) == 1
    drawn = sum(int(seg.split("h")[1].split("v")[0]) for seg in paths[0].get("d").split("z") if seg)
    assert drawn == sum(c for row in m for c in row)
    assert paths[0].get("fill") == "currentColor"
    assert not [e for e in root.iter() if e.tag.endswith("rect")]


def test_svg_background_and_color():
    root = ET.fromstring(qr.to_svg(qr.encode("HELLO"), dark="#123456", light="#ffffff"))
    rects = [e for e in root.iter() if e.tag.endswith("rect")]
    assert len(rects) == 1 and rects[0].get("fill") == "#ffffff"
    assert [e for e in root.iter() if e.tag.endswith("path")][0].get("fill") == "#123456"
